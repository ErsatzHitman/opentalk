fn is_combining(c: char) -> bool {
    ('\u{300}'..='\u{36F}').contains(&c)
}

fn compose_pair(base: char, mark: char) -> Option<char> {
    let key = (base as u32, mark as u32);
    COMPOSE
        .binary_search_by(|&(b, m, _)| (b, m).cmp(&key))
        .ok()
        .and_then(|i| char::from_u32(COMPOSE[i].2))
}

/// Compose combining marks onto their base letters. Borrows when the text has no combining marks.
pub fn nfc(s: &str) -> Cow<'_, str> {
    if !s.chars().any(is_combining) {
        return Cow::Borrowed(s);
    }
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        if is_combining(c)
            && let Some(prev) = out.chars().next_back()
            && let Some(composed) = compose_pair(prev, c)
        {
            out.pop();
            out.push(composed);
            continue;
        }
        out.push(c);
    }
    Cow::Owned(out)
}

#[cfg(test)]
mod tests {
    use super::nfc;

    #[test]
    fn composes_common_pairs() {
        assert_eq!(nfc("I\u{307}mza"), "İmza");
        assert_eq!(nfc("cafe\u{301}"), "café");
        assert_eq!(nfc("u\u{308}ber"), "über");
        assert_eq!(nfc("n\u{303}"), "ñ");
        assert_eq!(nfc("\u{438}\u{306}"), "й");
    }

    #[test]
    fn leaves_composed_and_plain_text_alone() {
        assert!(matches!(nfc("plain text"), std::borrow::Cow::Borrowed(_)));
        assert_eq!(nfc("İmza café"), "İmza café");
        assert_eq!(nfc("x\u{301}"), "x\u{301}");
    }

    #[test]
    fn table_is_sorted() {
        assert!(super::COMPOSE.windows(2).all(|w| (w[0].0, w[0].1) < (w[1].0, w[1].1)));
    }
}
